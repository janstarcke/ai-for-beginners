#!/usr/bin/env node
/**
 * build-git-history.mjs
 *
 * Reads `git log` for content-relevant files and writes a TypeScript module
 * with the resulting commit metadata. Used by the hidden /secret-import-history
 * page to show what was imported when.
 *
 * Design notes:
 *  - Coolify's Docker build excludes `.git/` (see .dockerignore). This script
 *    is therefore intended to run LOCALLY (or in CI with full history) and
 *    its output (`client/src/data/gitHistory.generated.ts`) is committed.
 *  - If `.git` is unavailable, the script exits 0 without writing — the
 *    previously-committed file remains the source of truth.
 *  - Filtered to commits that touched any tracked content file. Add more
 *    paths to TRACKED_PATHS if the data layer grows.
 *  - Uses execFileSync (no shell) — all args are hardcoded, no injection
 *    surface, but defense-in-depth is cheap.
 */

import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, "..");
const OUTPUT = path.join(ROOT, "client", "src", "data", "gitHistory.generated.ts");

const TRACKED_PATHS = [
  "client/src/data/skills.ts",
  "client/src/data/guide.ts",
  "client/src/data/importHistory.ts",
];

const MAX_COMMITS = "200";

function gitAvailable() {
  if (!existsSync(path.join(ROOT, ".git"))) return false;
  try {
    execFileSync("git", ["--version"], { cwd: ROOT, stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
}

function getCommits() {
  // Format: HEADER_MARK<H>|<h>|<aI>|<an>|<s>
  // Git places the pretty-format BEFORE the --name-only file list, separated
  // by a newline; an empty line separates one commit's files from the next
  // commit's header. We parse line-by-line and treat any line starting with
  // HEADER_MARK as the start of a new commit record.
  const SEP = "␟"; // unit separator inside the header
  const HEADER_MARK = "␝"; // group separator — picks the header line out of --name-only output

  const fmt = `${HEADER_MARK}%H${SEP}%h${SEP}%aI${SEP}%an${SEP}%s`;

  const args = [
    "log",
    `--pretty=format:${fmt}`,
    "--name-only",
    "-n",
    MAX_COMMITS,
    "--",
    ...TRACKED_PATHS,
  ];

  const raw = execFileSync("git", args, {
    cwd: ROOT,
    encoding: "utf8",
    maxBuffer: 8 * 1024 * 1024,
  });

  const commits = [];
  let current = null;

  for (const line of raw.split("\n")) {
    if (line.startsWith(HEADER_MARK)) {
      if (current) commits.push(current);
      const [hash, shortHash, date, author, subject] = line
        .slice(HEADER_MARK.length)
        .split(SEP);
      current = { hash, shortHash, date, author, subject, files: [] };
      continue;
    }
    if (!current) continue; // shouldn't happen
    const trimmed = line.trim();
    if (trimmed) current.files.push(trimmed);
  }
  if (current) commits.push(current);

  return commits;
}

function main() {
  if (!gitAvailable()) {
    console.log("[build-git-history] .git unavailable, leaving existing generated file in place.");
    process.exit(0);
  }

  const commits = getCommits();
  const generatedAt = new Date().toISOString();

  const banner = `// AUTO-GENERATED by scripts/build-git-history.mjs — DO NOT EDIT MANUALLY.
// Regenerate via \`pnpm history:update\`. The hidden /secret-import-history
// page joins this with client/src/data/importHistory.ts on the commit hash.

export interface GitCommit {
  hash: string;
  shortHash: string;
  date: string; // ISO 8601
  author: string;
  subject: string;
  files: string[];
}

export const gitHistoryGeneratedAt = ${JSON.stringify(generatedAt)};

export const gitHistory: GitCommit[] = ${JSON.stringify(commits, null, 2)};
`;

  writeFileSync(OUTPUT, banner, "utf8");
  console.log(`[build-git-history] wrote ${commits.length} commits → ${path.relative(ROOT, OUTPUT)}`);
}

main();
